/* ── Minimal PDF writer ───────────────────────────────────────────────── */
function escapePdfText(text) {
  return text.replace(/\\/g, "\\\\").replace(/\(/g, "\\(").replace(/\)/g, "\\)");
}

function buildPdf() {
  const lines = [];
  // Y positions flow from 740 downward (US Letter: 612 x 792).
  let y = 740;

  lines.push(["F1", 22, 0, y, content.name]);
  y -= 26;
  lines.push(["F2", 12, 0, y, content.role]);
  y -= 20;
  lines.push(["F2", 9.5, 0, y, content.contact]);
  y -= 14;
  lines.push(["RULE"]);
  y -= 14;

  for (const section of content.sections) {
    lines.push(["F1", 12.5, 0, y, section.heading]);
    y -= 6;
    lines.push(["RULE-THIN"]);
    y -= 16;
    for (const line of section.lines) {
      const indented = line.startsWith("  ");
      lines.push([
        "F2",
        indented ? 9.5 : 10.5,
        indented ? 24 : 0,
        y,
        indented ? line.trimStart() : line,
      ]);
      y -= indented ? 13.5 : 16;
    }
    y -= 12;
  }

  lines.push(["F2", 8, 0, 60, content.footnote]);

  const parts = [];
  for (const [font, size, x, yPos, text] of lines) {
    if (font === "RULE") {
      parts.push(`0.55 0.43 1 RG 1.2 w 57 ${yPos} m 555 ${yPos} l S`);
    } else if (font === "RULE-THIN") {
      parts.push(`0.55 0.43 1 RG 0.5 w 57 ${yPos} m 555 ${yPos} l S`);
    } else if (font === "F1") {
      parts.push(`BT /F1 ${size} Tf 0.09 0.1 0.16 rg 57 ${yPos} Td (${escapePdfText(text)}) Tj ET`);
    } else {
      parts.push(`BT /F2 ${size} Tf 0.25 0.28 0.38 rg 57 ${yPos} Td (${escapePdfText(text)}) Tj ET`);
    }
  }

  const stream = parts.join("\n");

  const objects = [];
  objects[1] = "<< /Type /Catalog /Pages 2 0 R >>";
  objects[2] = "<< /Type /Pages /Kids [3 0 R] /Count 1 >>";
  objects[3] =
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >>";
  objects[4] = "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>";
  objects[5] = "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>";
  objects[6] = `<< /Length ${Buffer.byteLength(stream)} >>\nstream\n${stream}\nendstream`;

  let pdf = "%PDF-1.4\n";
  const offsets = [0];
  for (let i = 1; i < objects.length; i++) {
    offsets[i] = Buffer.byteLength(pdf);
    pdf += `${i} 0 obj\n${objects[i]}\nendobj\n`;
  }

  const xrefStart = Buffer.byteLength(pdf);
  const count = objects.length;
  pdf += `xref\n0 ${count}\n0000000000 65535 f \n`;
  for (let i = 1; i < count; i++) {
    pdf += `${String(offsets[i]).padStart(10, "0")} 00000 n \n`;
  }
  pdf += `trailer\n<< /Size ${count} /Root 1 0 R >>\nstartxref\n${xrefStart}\n%%EOF`;

  return Buffer.from(pdf, "binary");
}

writeFileSync(join(root, "public", "resume.pdf"), buildPdf());
console.log("✓ Placeholder resume written to /public/resume.pdf");
